"""Generate typed .NET constants from the one editable backend resource catalog (stdlib only)."""
import argparse
import json
from pathlib import Path
import re

REPO_ROOT = Path(__file__).resolve().parents[1]
ROOT = REPO_ROOT / "backend" / "Shared" / "HackthonSpurs.Resources"
SOURCE = ROOT / "backend-resources.json"
TARGET = ROOT / "BackendResources.g.cs"


def unique(pairs):
    """Read object pairs without silently accepting a duplicate resource name."""
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate resource: {key}")
        result[key] = value
    return result


def identifier(value):
    """Validate value as a public PascalCase C# resource identifier."""
    if not re.fullmatch(r"[A-Z][A-Za-z0-9]*", value):
        raise ValueError(f"Invalid identifier: {value}")
    return value


def generate(catalog):
    """Render deterministic C# from catalog, rejecting duplicate codes and invalid status mappings."""
    lines = ["// <auto-generated /> Edit backend-resources.json and run tools/generate_backend_resources.py.",
             "#nullable enable", "using System.Collections.Frozen;", "", "namespace HackthonSpurs.Resources;", "",
             "public static class Errors", "{"]
    codes = set()
    entries = catalog["Errors"]
    for key, entry in entries.items():
        code, message = entry["code"], entry["message"]
        status, reader = entry.get("status"), entry.get("reader", False)
        if (code in codes or not re.fullmatch(r"[a-z][a-z0-9_]*", code) or not message.strip() or
            (status is not None and not 400 <= status <= 599) or (reader and status is None)):
            raise ValueError(f"Invalid error definition: {key}")
        codes.add(code)
        args = [json.dumps(code), json.dumps(message), str(status) if status else "null", str(reader).lower()]
        lines.append(f"    public static readonly BackendError {identifier(key)} = new({', '.join(args)});")
    lines.extend(["", "    public static readonly FrozenDictionary<string, BackendError> ByCode =",
                  "        new BackendError[]", "        {"])
    names = list(entries)
    for offset in range(0, len(names), 4):
        lines.append("            " + ", ".join(names[offset:offset + 4]) + ",")
    lines += ["        }.ToFrozenDictionary(error => error.Code, StringComparer.Ordinal);", "}"]
    for group, values in catalog.items():
        if group == "Errors":
            continue
        lines.extend(["", f"public static class {identifier(group)}", "{"])
        for key, value in values.items():
            kind = {int: "int", str: "string", float: "double"}[type(value)]
            lines.append(f"    public const {kind} {identifier(key)} = {json.dumps(value, ensure_ascii=False)};")
        lines.append("}")
    return "\n".join(lines) + "\n"


def browser_messages(catalog):
    """Project only safe public error text from catalog; never expose settings to the browser."""
    lines = ["// Generated from the backend resource catalog; do not edit.",
             "export const backendMessages: ReadonlyMap<string, string> = new Map(["]
    for entry in catalog["Errors"].values():
        pair = [entry["code"], entry.get("uiMessage", entry["message"])]
        lines.append("  " + json.dumps(pair, ensure_ascii=False) + ",")
    return "\n".join(lines + ["]);", "export const unknownProblem = " +
                             json.dumps(catalog["ResourceText"]["UnknownProblem"]) + ";", ""])


def main():
    """Regenerate the binding, or check for drift when --check is supplied."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    catalog = json.loads(SOURCE.read_text(encoding="utf-8"), object_pairs_hook=unique)
    web = REPO_ROOT / "frontend/src/api/backendMessages.generated.ts"
    for path, result in [(TARGET, generate(catalog)), (web, browser_messages(catalog))]:
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != result:
                raise SystemExit(f"Stale {path.name}: run python -B tools/generate_backend_resources.py")
        else:
            path.write_text(result, encoding="utf-8")
    if args.check:
        print("PASS: .NET and public browser backend resource bindings are current.")



if __name__ == "__main__":
    main()
